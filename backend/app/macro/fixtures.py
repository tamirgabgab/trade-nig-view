"""Offline macro series (``OFFLINE=1`` and tests): ``<fixtures>/macro/<id>.csv``, ``date,value``.

Generated by ``scripts/make_macro_fixtures.py`` (the Bank of Israel is reachable from anywhere).
"""

from __future__ import annotations

import csv
from pathlib import Path

from app.data.providers.base import ProviderError
from app.macro.boi import period_day
from app.macro.series import MacroSeries, SeriesSpec


def read_macro_fixture(path: Path) -> MacroSeries:
    """The snapshot, sorted, one value per day; an empty or unreadable file is a ProviderError."""
    with path.open(newline="", encoding="utf-8") as handle:
        rows = list(csv.DictReader(handle))
    try:
        series = MacroSeries.from_pairs({period_day(r["date"]): float(r["value"]) for r in rows})
    except (KeyError, ValueError) as exc:
        raise ProviderError(f"{path.name}: unreadable macro fixture ({exc})") from exc
    if len(series) == 0:
        raise ProviderError(f"{path.name}: empty macro fixture")
    return series


def write_macro_fixture(path: Path, series: MacroSeries) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    dates = series.days.astype("datetime64[D]")
    with path.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.writer(handle, lineterminator="\n")
        writer.writerow(("date", "value"))
        for day, value in zip(dates, series.values, strict=True):
            writer.writerow((str(day), repr(float(value))))


class MacroFixtureSource:
    id = "fixtures"

    def __init__(self, root: Path) -> None:
        self._root = root / "macro"

    def fetch(self, spec: SeriesSpec) -> MacroSeries:
        path = self._root / f"{spec.id}.csv"
        if not path.is_file():
            raise ProviderError(f"No offline fixture for macro series {spec.id}")
        return read_macro_fixture(path)
