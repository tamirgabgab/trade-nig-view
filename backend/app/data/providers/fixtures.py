"""Offline provider serving committed CSV snapshots (``OFFLINE=1`` and tests).

Layout under the fixtures root (one file per symbol, file name from :func:`fixture_filename`)::

    daily/<symbol>.csv   date,open,high,low,close,adj_close,volume      (date = session date)
    1h/<symbol>.csv      time,open,high,low,close,volume                (time = UTC bar start,
                                                                         ISO 8601 with 'Z')

Generated by ``scripts/make_fixtures.py``.
"""

from __future__ import annotations

import csv
import re
from datetime import UTC, date, datetime
from pathlib import Path

import numpy as np

from app.data.providers.base import ProviderError
from app.models.bars import SECONDS_PER_DAY, BarFrame, date_to_ts
from app.models.symbols import SymbolInfo

CSV_COLUMNS = ("date", "open", "high", "low", "close", "adj_close", "volume")
HOURLY_CSV_COLUMNS = ("time", "open", "high", "low", "close", "volume")
DAILY_DIR = "daily"
HOURLY_DIR = "1h"


def fixture_filename(symbol: str) -> str:
    """Filesystem-safe name: ``^GSPC`` -> ``_GSPC.csv``, ``CL=F`` -> ``CL_F.csv``."""
    return re.sub(r"[^A-Za-z0-9.-]", "_", symbol) + ".csv"


def read_fixture(path: Path) -> BarFrame:
    with path.open(newline="", encoding="utf-8") as handle:
        rows = list(csv.DictReader(handle))
    if not rows:
        return BarFrame.empty()
    missing = set(CSV_COLUMNS) - set(rows[0])
    if missing:
        raise ProviderError(f"{path.name}: missing columns {sorted(missing)}")
    days = np.array([row["date"] for row in rows], dtype="datetime64[D]").astype(np.int64)
    return BarFrame(
        time=days * SECONDS_PER_DAY,
        **{
            name: np.array([float(row[name]) for row in rows], dtype=np.float64)
            for name in CSV_COLUMNS[1:]
        },
    )


def _iso_utc(ts: int) -> str:
    return datetime.fromtimestamp(ts, UTC).strftime("%Y-%m-%dT%H:%M:%SZ")


def _parse_iso_utc(text: str) -> int:
    return int(datetime.strptime(text, "%Y-%m-%dT%H:%M:%SZ").replace(tzinfo=UTC).timestamp())


def read_hourly_fixture(path: Path) -> BarFrame:
    with path.open(newline="", encoding="utf-8") as handle:
        rows = list(csv.DictReader(handle))
    if not rows:
        return BarFrame.empty()
    missing = set(HOURLY_CSV_COLUMNS) - set(rows[0])
    if missing:
        raise ProviderError(f"{path.name}: missing columns {sorted(missing)}")
    columns = {
        name: np.array([float(row[name]) for row in rows], dtype=np.float64)
        for name in HOURLY_CSV_COLUMNS[1:]
    }
    return BarFrame(
        time=np.array([_parse_iso_utc(row["time"]) for row in rows], dtype=np.int64),
        adj_close=columns["close"].copy(),
        **columns,
    )


def write_hourly_fixture(path: Path, frame: BarFrame) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.writer(handle, lineterminator="\n")
        writer.writerow(HOURLY_CSV_COLUMNS)
        for i in range(len(frame)):
            writer.writerow(
                [
                    _iso_utc(int(frame.time[i])),
                    repr(float(frame.open[i])),
                    repr(float(frame.high[i])),
                    repr(float(frame.low[i])),
                    repr(float(frame.close[i])),
                    repr(float(frame.volume[i])),
                ]
            )


def write_fixture(path: Path, frame: BarFrame) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    days = (frame.time // SECONDS_PER_DAY).astype("datetime64[D]")
    with path.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.writer(handle, lineterminator="\n")
        writer.writerow(CSV_COLUMNS)
        for i in range(len(frame)):
            writer.writerow(
                [
                    str(days[i]),
                    repr(float(frame.open[i])),
                    repr(float(frame.high[i])),
                    repr(float(frame.low[i])),
                    repr(float(frame.close[i])),
                    repr(float(frame.adj_close[i])),
                    repr(float(frame.volume[i])),
                ]
            )


class FixtureProvider:
    """Serves bars from ``<root>/daily/`` and ``<root>/1h/`` (see the module docstring)."""

    id = "fixtures"

    def __init__(self, root: Path) -> None:
        self._root = root

    def _path(self, symbol: SymbolInfo) -> Path:
        return self._root / DAILY_DIR / fixture_filename(symbol.symbol)

    def _hourly_path(self, symbol: SymbolInfo) -> Path:
        return self._root / HOURLY_DIR / fixture_filename(symbol.symbol)

    def supports(self, symbol: SymbolInfo) -> bool:
        return self._path(symbol).is_file()

    def fetch_daily(self, symbol: SymbolInfo, start: date, end: date) -> BarFrame:
        path = self._path(symbol)
        if not path.is_file():
            raise ProviderError(f"No offline fixture for {symbol.symbol}")
        frame = read_fixture(path)
        mask = (frame.time >= date_to_ts(start)) & (frame.time <= date_to_ts(end))
        return frame.take(mask)

    def supports_hourly(self, symbol: SymbolInfo) -> bool:
        return self._hourly_path(symbol).is_file()

    def fetch_hourly(self, symbol: SymbolInfo, start: date, end: date) -> BarFrame:
        path = self._hourly_path(symbol)
        if not path.is_file():
            raise ProviderError(f"No offline 1h fixture for {symbol.symbol}")
        frame = read_hourly_fixture(path)
        mask = (frame.time >= date_to_ts(start)) & (frame.time < date_to_ts(end) + SECONDS_PER_DAY)
        return frame.take(mask)
